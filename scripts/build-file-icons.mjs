// Generates src/features/fileIcons/iconSet.generated.js from the
// material-icon-theme package (MIT). Run with `npm run icons:build`.
//
// Only the allowlisted icon ids are embedded, and the manifest's file/folder
// mapping tables are filtered down to those ids, so the shipped bundle carries
// a small curated set instead of the full ~1 MB theme. Folder-name variants
// such as `_rust`, `-rust` and `__rust__` are dropped: the canonical `rust`
// key covers them.
