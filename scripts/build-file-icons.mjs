/**
 * A folder-name key is canonical when it is not a decorative variant of
 * another key: `_rust`, `-rust`, `__rust__`, `rust_` are all dropped, while
 * real hidden folders (`.github`, `.vscode`) are kept.
 */
function isCanonicalFolderName(key) {
  if (/^_+/.test(key) || /_+$/.test(key)) return false;
  if (/^-+/.test(key) || /-+$/.test(key)) return false;
  return true;
}

function loadManifest() {
  const dir = path.dirname(require.resolve('material-icon-theme/package.json'));
  const manifest = JSON.parse(readFileSync(path.join(dir, 'dist', 'material-icons.json'), 'utf8'));
  return { dir, manifest };
}

/**
 * Material Icon Theme authors its icons in different coordinate systems, so the
 * `viewBox` is captured next to the body; rendering every body under a single
 * fixed viewBox would crop all but the 16×16 icons.
 */
function iconBody(dir, manifest, id) {
  const def = manifest.iconDefinitions[id];
  if (!def) throw new Error(`unknown icon id: ${id}`);
  const file = path.resolve(dir, 'dist', def.iconPath);
  const svg = readFileSync(file, 'utf8');
  const viewBox = svg.match(/<svg[^>]*\sviewBox="([^"]+)"/)?.[1] || '0 0 16 16';
  const body = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s+/g, ' ')
    .trim();
  return { viewBox, body };
}

function filterTable(table, allow, keyFilter) {
  const out = {};
  for (const key of Object.keys(table)) {
    if (allow.has(table[key]) && (!keyFilter || keyFilter(key))) out[key] = table[key];
  }
  return out;
}

function main() {
  const { dir, manifest } = loadManifest();
  const allow = new Set(ICON_IDS);
  const icons = {};
  const viewBoxes = {};
  for (const id of allow) {
    const icon = iconBody(dir, manifest, id);
    icons[id] = icon.body;
    viewBoxes[id] = icon.viewBox;
  }

  const output = `// Generated by scripts/build-file-icons.mjs. Do not edit by hand.
// Source: material-icon-theme (MIT). Run \`npm run icons:build\` to refresh.
export const ICON_BODIES = ${JSON.stringify(icons)};
export const ICON_VIEWBOXES = ${JSON.stringify(viewBoxes)};
export const EXTENSIONS = ${JSON.stringify(filterTable(manifest.fileExtensions, allow))};
export const FILE_NAMES = ${JSON.stringify(filterTable(manifest.fileNames, allow))};
export const FOLDER_NAMES = ${JSON.stringify(filterTable(manifest.folderNames, allow, isCanonicalFolderName))};
export const DEFAULT_FILE = 'file';
export const DEFAULT_FOLDER = 'folder';
`;

  const target = path.join(root, 'src', 'features', 'fileIcons', 'iconSet.generated.js');
  mkdirSync(path.dirname(target), { recursive: true });
  writeFileSync(target, output);
  const kb = (Buffer.byteLength(output) / 1024).toFixed(1);
  console.log(`file-icons: wrote ${allow.size} icons, ${kb} KB -> ${path.relative(root, target)}`);
}

main();
